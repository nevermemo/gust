//! Module-level `const` items in the macro (slice m11.g3, D205; expressions: slice m11.cexpr, D210): the accepted
//! forms and their lowering to `static const` lines, and the refusals (GUST-E0127, and the codes the unchanged items
//! keep).

use crate::{
    diagnostics::{
        Code,
        testing::{assert_code_for, parse_str},
    },
    expand::kernel_options,
    slang::emit_kernel,
    validate::validate_module,
};

const HEADER: &str = "// Generated by GUST from Rust syntax. Slang is the compiler backend.\n\n";

/// `items` and two kernels, `first` and `second`, whose bodies are `first_body` and `second_body`.
fn module(items: &str, first_body: &str, second_body: &str) -> String {
    format!(
        "mod m {{
    {items}
    #[kernel(workgroup_size(64, 1, 1))]
    pub fn first(id: SV_DispatchThreadID, mut out: RWStructuredBuffer<u32>) {{ {first_body} }}
    #[kernel(workgroup_size(64, 1, 1))]
    pub fn second(id: SV_DispatchThreadID, mut out: RWStructuredBuffer<u32>) {{ {second_body} }}
}}"
    )
}

/// The text of every kernel of `source`, one after the other, each behind a `// ==== kernel name ====` line.
fn lower(source: &str) -> syn::Result<Vec<(String, String)>> {
    let module: syn::ItemMod = parse_str(source)?;
    validate_module(&module)?;
    let mut texts = Vec::new();
    for item in &module.content.as_ref().unwrap().1 {
        let syn::Item::Fn(function) = item else {
            continue;
        };
        let Some(options) = kernel_options(function)? else {
            continue;
        };
        let text = emit_kernel(&module, function, options)?
            .source
            .replace("\r\n", "\n");
        texts.push((function.sig.ident.to_string(), text));
    }
    Ok(texts)
}

fn refused(source: &str, code: Code) {
    let error = lower(source).expect_err(source);
    assert_code_for(&error, code, source);
}

fn accepted(source: &str) -> Vec<(String, String)> {
    lower(source).unwrap_or_else(|error| panic!("{error}: {source}"))
}

#[test]
fn a_const_of_each_type_is_a_static_const_line_in_the_text_of_every_kernel() {
    let source = module(
        "pub const WIDTH: u32 = 4096;
    /// Documented, with a lint level.
    #[allow(dead_code)]
    const OFFSET: i32 = -7;
    pub(crate) const SCALE: f32 = 0.5;
    const ON: bool = true;
    fn bias(x: u32) -> u32 { if ON { x + WIDTH } else { x } }",
        "out[id.x] = bias(id.x) + WIDTH;",
        "let v: i32 = OFFSET; let s: f32 = SCALE * 2.0; out[id.x] = v as u32 + s as u32;",
    );
    let texts = accepted(&source);
    assert_eq!(texts.len(), 2);
    let lines = "static const uint WIDTH = 4096;\n\
                 static const int OFFSET = -7;\n\
                 static const float SCALE = 0.5;\n\
                 static const bool ON = true;\n\n";
    for (name, text) in &texts {
        let expected = format!("{HEADER}{lines}");
        assert!(
            text.starts_with(&expected),
            "kernel {name}:\n{text}\nstarts with\n{expected}"
        );
        // The helper and the kernel read the names as they are written.
        assert!(text.contains("if (ON)"), "{text}");
        assert!(text.contains("(x + WIDTH)"), "{text}");
    }
    assert!(
        texts[0].1.contains("(bias(id.x) + WIDTH)"),
        "{}",
        texts[0].1
    );
    assert!(texts[1].1.contains("int v = OFFSET;"), "{}", texts[1].1);
}

