/// What a module const does where a literal is required: pinned as it is today, not as a feature.
#[test]
fn a_const_as_an_array_length_or_workgroup_size_is_not_evaluated() {
    // The array length is a literal (E0216); a constant is no literal.
    refused(
        &module(
            "const N: u32 = 4;",
            "let a: [u32; N] = [1u32, 2u32, 3u32, 4u32]; out[id.x] = a[0];",
            "out[id.x] = id.x;",
        ),
        Code::ArrayLength,
    );
    // `workgroup_size(N)` reads the integer literals of the attribute only.
    let source = "mod m {
    const N: u32 = 64;
    #[kernel(workgroup_size(N, 1, 1))]
    pub fn first(id: SV_DispatchThreadID, mut out: RWStructuredBuffer<u32>) { out[id.x] = 1; }
}";
    refused(source, Code::MalformedKernelAttribute);
}
