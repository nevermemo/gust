//! Module-level `const` items in the macro (slice m11.g3, D205): the accepted form and its lowering to `static const`
//! lines, and the refusals (GUST-E0127, and the codes the unchanged items keep).

use crate::{
    diagnostics::{
        Code,
        testing::{assert_code_for, parse_str},
    },
    expand::kernel_options,
    slang::emit_kernel,
    validate::validate_module,
};

const HEADER: &str = "// Generated by GUST from Rust syntax. Slang is the compiler backend.\n\n";

/// `items` and two kernels, `first` and `second`, whose bodies are `first_body` and `second_body`.
fn module(items: &str, first_body: &str, second_body: &str) -> String {
    format!(
        "mod m {{
    {items}
    #[kernel(workgroup_size(64, 1, 1))]
    pub fn first(id: SV_DispatchThreadID, mut out: RWStructuredBuffer<u32>) {{ {first_body} }}
    #[kernel(workgroup_size(64, 1, 1))]
    pub fn second(id: SV_DispatchThreadID, mut out: RWStructuredBuffer<u32>) {{ {second_body} }}
}}"
    )
}

/// The text of every kernel of `source`, one after the other, each behind a `// ==== kernel name ====` line.
fn lower(source: &str) -> syn::Result<Vec<(String, String)>> {
    let module: syn::ItemMod = parse_str(source)?;
    validate_module(&module)?;
    let mut texts = Vec::new();
    for item in &module.content.as_ref().unwrap().1 {
        let syn::Item::Fn(function) = item else {
            continue;
        };
        let Some(options) = kernel_options(function)? else {
            continue;
        };
        let text = emit_kernel(&module, function, options)?
            .source
            .replace("\r\n", "\n");
        texts.push((function.sig.ident.to_string(), text));
    }
    Ok(texts)
}

fn refused(source: &str, code: Code) {
    let error = lower(source).expect_err(source);
    assert_code_for(&error, code, source);
}

fn accepted(source: &str) -> Vec<(String, String)> {
    lower(source).unwrap_or_else(|error| panic!("{error}: {source}"))
}

#[test]
fn a_const_of_each_type_is_a_static_const_line_in_the_text_of_every_kernel() {
    let source = module(
        "pub const WIDTH: u32 = 4096;
    /// Documented, with a lint level.
    #[allow(dead_code)]
    const OFFSET: i32 = -7;
    pub(crate) const SCALE: f32 = 0.5;
    const ON: bool = true;
    fn bias(x: u32) -> u32 { if ON { x + WIDTH } else { x } }",
        "out[id.x] = bias(id.x) + WIDTH;",
        "let v: i32 = OFFSET; let s: f32 = SCALE * 2.0; out[id.x] = v as u32 + s as u32;",
    );
    let texts = accepted(&source);
    assert_eq!(texts.len(), 2);
    let lines = "static const uint WIDTH = 4096;\n\
                 static const int OFFSET = -7;\n\
                 static const float SCALE = 0.5;\n\
                 static const bool ON = true;\n\n";
    for (name, text) in &texts {
        let expected = format!("{HEADER}{lines}");
        assert!(
            text.starts_with(&expected),
            "kernel {name}:\n{text}\nstarts with\n{expected}"
        );
        // The helper and the kernel read the names as they are written.
        assert!(text.contains("if (ON)"), "{text}");
        assert!(text.contains("(x + WIDTH)"), "{text}");
    }
    assert!(
        texts[0].1.contains("(bias(id.x) + WIDTH)"),
        "{}",
        texts[0].1
    );
    assert!(texts[1].1.contains("int v = OFFSET;"), "{}", texts[1].1);
}

#[test]
fn the_literal_keeps_its_type_in_slang() {
    let source = module(
        "const BIG: u32 = 4294967295;
    const SUFFIXED: u32 = 7u32;
    const LOW: i32 = -2147483648;
    const NEG: i32 = -5i32;
    const POS: i32 = 9i32;
    const TINY: f32 = 1.5f32;
    const BELOW: f32 = -0.25;
    const WHOLE: f32 = 2f32;
    const OFF: bool = false;
    const ALIAS: uint = 3;
    const FLOAT_ALIAS: float = 1.0;",
        "out[id.x] = BIG;",
        "out[id.x] = ALIAS;",
    );
    let texts = accepted(&source);
    let lines = "static const uint BIG = uint(4294967295);\n\
                 static const uint SUFFIXED = uint(7);\n\
                 static const int LOW = -2147483648;\n\
                 static const int NEG = -int(5);\n\
                 static const int POS = int(9);\n\
                 static const float TINY = float(1.5);\n\
                 static const float BELOW = -0.25;\n\
                 static const float WHOLE = float(2.0);\n\
                 static const bool OFF = false;\n\
                 static const uint ALIAS = 3;\n\
                 static const float FLOAT_ALIAS = 1.0;\n\n";
    for (_, text) in &texts {
        assert!(text.starts_with(&format!("{HEADER}{lines}")), "{text}");
    }
}

#[test]
fn a_const_named_like_a_collision_entry_is_renamed_at_the_declaration_and_the_use() {
    let source = module(
        "#[allow(non_upper_case_globals)]
    const min: u32 = 3;
    fn lift(x: u32) -> u32 { x + min }",
        "out[id.x] = lift(id.x) + min;",
        "out[id.x] = min;",
    );
    for (_, text) in accepted(&source) {
        assert!(
            text.contains("\nstatic const uint __gust_r_min = 3;\n"),
            "{text}"
        );
        assert!(text.contains("(x + __gust_r_min)"), "{text}");
        assert!(!text.contains(" min "), "{text}");
    }
}

#[test]
fn a_module_without_a_const_gets_no_extra_line() {
    let source = module("", "out[id.x] = id.x;", "out[id.x] = 1;");
    for (_, text) in accepted(&source) {
        assert!(!text.contains("static const"), "{text}");
        assert!(text.starts_with(HEADER), "{text}");
        assert!(!text.starts_with(&format!("{HEADER}\n")), "{text}");
    }
}

#[test]
fn a_const_may_stand_where_a_value_does() {
    let source = module(
        "const N: u32 = 8; const LIMIT: i32 = 3;",
        "let mut acc: u32 = 0; for i in 0u32..N { acc += i; } if (id.x as i32) < LIMIT { acc += N; } out[id.x] = acc;",
        "match id.x { 0 => { out[0] = N; } _ => { out[id.x] = 0; } }",
    );
    accepted(&source);
}

#[test]
fn another_type_is_e0127() {
    for ty in [
        "usize",
        "u64",
        "f64",
        "Vec2",
        "[u32; 2]",
        "&'static str",
        "S",
        "(u32, u32)",
        "Option<u32>",
        "std::primitive::u32",
    ] {
        refused(
            &module(
                &format!("pub struct S {{ pub a: u32 }} const K: {ty} = 1;"),
                "out[id.x] = id.x;",
                "out[id.x] = id.x;",
            ),
            Code::ConstForm,
        );
    }
}

