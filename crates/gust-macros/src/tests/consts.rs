#[test]
fn a_const_name_as_a_pattern_is_e0127() {
    for body in [
        // An integer `match` (the `match` rules refuse a name arm as E0521 where no const is named).
        "match id.x { K => { out[0] = 1; } _ => { out[0] = 0; } }",
        "match id.x { 0 | K => { out[0] = 1; } _ => { out[0] = 0; } }",
        // `if let` takes a name as the payload of `Some`: rustc compares with the const, the lowering would bind.
        "let o: Option<u32> = Some(id.x); if let Some(K) = o { out[0] = 1; }",
        // A binding of the name: also an error of rustc (a refutable pattern), refused here first.
        "let K = 1u32; out[0] = K;",
        "for K in 0u32..4u32 { out[0] = K; }",
    ] {
        refused(
            &module("const K: u32 = 1;", body, "out[id.x] = id.x;"),
            Code::ConstForm,
        );
    }
    // A parameter and a closure parameter.
    refused(
        &module(
            "const K: u32 = 1; fn f(K: u32) -> u32 { 1 }",
            "out[id.x] = id.x;",
            "out[id.x] = id.x;",
        ),
        Code::ConstForm,
    );
    refused(
        &module(
            "const K: u32 = 1;",
            "let f = |K: u32| -> u32 { K + 1 }; out[id.x] = f(1);",
            "out[id.x] = id.x;",
        ),
        Code::ConstForm,
    );
    // An enum `match`, with the const of the same name as a variant path's last segment, is not a pattern of the const.
    accepted(&module(
        "const K: u32 = 1;
    #[derive(PartialEq, Eq)] pub enum E { K, B }",
        "let e = E::K; match e { E::K => { out[0] = K; } E::B => { out[0] = 0; } }",
        "out[id.x] = id.x;",
    ));
}

