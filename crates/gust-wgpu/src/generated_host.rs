use std::{fmt, fmt::Write as _};

use gust::{Access, KernelDescriptor, ParameterKind};

use crate::{Error, validate_kernel};

/// Render the descriptor-specific wgpu host code used to encode a dispatch.
///
/// The generated source intentionally starts with already-created `wgpu::Buffer`
/// parameters so the binding layout, shader/pipeline construction, and dispatch
/// mechanics remain easy to inspect without including upload/readback policy.
///
/// The generated `encode` takes the launch size in one of two shapes (m7.d). A kernel whose workgroup is
/// one-dimensional (`y` and `z` are 1) takes `element_count: u32` and dispatches `element_count.div_ceil(x)`
/// workgroups along x only, so it cannot be given a `y` or `z` extent. A kernel with a two- or three-dimensional
/// workgroup takes `extent: [u32; 3]` and divides each axis by the workgroup size. Neither shape checks the device
/// limits or the invocation cap: the generated host bypasses the checks `HeadlessDevice` makes (D36).
///
/// The snippet is a compute host. A `pixel` kernel is [`Error::ShapeUnsupported`]: it runs as a render pass
/// (slice mx.p1b), and no pixel snippet exists in MX.
pub fn render_wgpu_source(kernel: &KernelDescriptor) -> Result<String, Error> {
    crate::render::require_grid(
        kernel,
        "the generated host snippet is a compute host; no pixel snippet exists",
    )?;
    let resources = validate_kernel(kernel)?;
    let pipeline_type = format!(
        "{}{}Pipeline",
        rust_type_identifier(kernel.module),
        rust_type_identifier(kernel.name)
    );
    let mut source = String::new();
    write_line(
        &mut source,
        format_args!("// @generated by gust-wgpu for {}", kernel.qualified_name()),
    );
    write_line(
        &mut source,
        format_args!(
            "// Shader source: the kernel's embedded WGSL artifact (checked by gust::artifact::verify_artifact), else Rust -> Slang -> WGSL"
        ),
    );
    write_line(
        &mut source,
        format_args!(
            "// Compiling the Slang at run time (gust::slang::compile_wgsl) needs gust's `slang-runtime` feature, which is off by default;"
        ),
    );
    write_line(
        &mut source,
        format_args!(
            "// without it, replace the `None` arm below with a panic or an error that names `cargo gust build`, which writes the artifact."
        ),
    );
    for parameter in &resources {
        let binding = parameter.binding.expect("validated resource binding");
        let Some(layout) = parameter.resource_layout else {
            // A sampler has no element contract.
            write_line(
                &mut source,
                format_args!(
                    "// @group({}) @binding({}) {}: sampler",
                    binding.group, binding.binding, parameter.name
                ),
            );
            continue;
        };
        write_line(
            &mut source,
            format_args!(
                "// @group({}) @binding({}) {}: {} [{}; size={}, align={}, stride={}]",
                binding.group,
                binding.binding,
                parameter.name,
                layout.element.name,
                match layout.rules {
                    gust::ShaderLayoutRules::StorageV1 => "storage-v1",
                    gust::ShaderLayoutRules::StorageV2 => "storage-v2",
                    gust::ShaderLayoutRules::Std140V1 => "std140-v1",
                    gust::ShaderLayoutRules::TextureV1(_) => "texture-v1",
                },
                layout.element.size,
                layout.element.alignment,
                layout.element_stride,
            ),
        );
        render_struct_fields(&mut source, parameter.name, layout.element, 0);
    }
    write_line(
        &mut source,
        format_args!("// Construct this pipeline once, then reuse encode() for every dispatch."),
    );
    write_line(
        &mut source,
        format_args!("// Call encode() repeatedly on one command encoder to batch dispatches."),
    );
    source.push('\n');
    write_line(&mut source, format_args!("pub struct {pipeline_type} {{"));
    source.push_str("    _shader: wgpu::ShaderModule,\n");
    source.push_str("    bind_group_layout: wgpu::BindGroupLayout,\n");
    source.push_str("    _pipeline_layout: wgpu::PipelineLayout,\n");
    source.push_str("    pipeline: wgpu::ComputePipeline,\n");
    source.push_str("}\n\n");
    write_line(&mut source, format_args!("impl {pipeline_type} {{"));
    // A kernel with a sampler or a sampled float texture has two layout variants (module docs of `texture.rs`): `new`
    // then takes whether the device enabled `float32-filterable` and renders the layout entries from it.
    if resources
        .iter()
        .any(|parameter| follows_filtering(parameter))
    {
        source.push_str(
            "    /// `float32_filterable` is whether `device` was opened with the `float32-filterable` feature\n    /// (`HeadlessDevice::float32_filterable`): float textures are then filterable and samplers filtering.\n    pub fn new(\n        device: &wgpu::Device,\n        descriptor: &gust::KernelDescriptor,\n        float32_filterable: bool,\n    ) -> Self {\n",
        );
    } else {
        source.push_str(
            "    pub fn new(device: &wgpu::Device, descriptor: &gust::KernelDescriptor) -> Self {\n",
        );
    }
    write_line(
        &mut source,
        format_args!(
            "        let label = \"{}::{}\";",
            kernel.module, kernel.name
        ),
    );
    source.push_str(
        "        let wgsl = match descriptor\n            .artifacts\n            .iter()\n            .find(|artifact| artifact.format == gust::Format::Wgsl)\n        {\n            Some(artifact) => {\n                let verified = gust::artifact::verify_artifact(descriptor, artifact)\n                    .expect(\"verify the embedded WGSL artifact\");\n                String::from_utf8(verified.compiled.artifact).expect(\"WGSL is UTF-8\")\n            }\n            None => gust::slang::compile_wgsl(descriptor).expect(\"compile generated Slang\"),\n        };\n",
    );
    source.push_str(
        "        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {\n",
    );
    source.push_str("            label: Some(label),\n");
    source.push_str("            source: wgpu::ShaderSource::Wgsl(wgsl.into()),\n");
    source.push_str("        });\n\n");
    source.push_str("        let layout_entries = [\n");
    for parameter in &resources {
        let binding = parameter.binding.expect("validated resource binding");
        source.push_str("            wgpu::BindGroupLayoutEntry {\n");
        write_line(
            &mut source,
            format_args!("                binding: {},", binding.binding),
        );
        source.push_str("                visibility: wgpu::ShaderStages::COMPUTE,\n");
        match parameter.kind {
            ParameterKind::Texture | ParameterKind::Sampler => {
                render_texture_type(&mut source, parameter)?;
            }
            _ => {
                source.push_str("                ty: wgpu::BindingType::Buffer {\n");
                if parameter.kind == ParameterKind::Uniform {
                    source.push_str("                    ty: wgpu::BufferBindingType::Uniform,\n");
                } else {
                    write_line(
                        &mut source,
                        format_args!(
                            "                    ty: wgpu::BufferBindingType::Storage {{ read_only: {} }},",
                            parameter.access == Access::ReadOnly
                        ),
                    );
                }
                source.push_str("                    has_dynamic_offset: false,\n");
                source.push_str("                    min_binding_size: None,\n");
                source.push_str("                },\n");
            }
        }
        source.push_str("                count: None,\n");
        source.push_str("            },\n");
    }
    source.push_str("        ];\n");
    source.push_str(
        "        let bind_group_layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {\n            label: Some(label),\n            entries: &layout_entries,\n        });\n",
    );
    source.push_str(
        "        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {\n            label: Some(label),\n            bind_group_layouts: &[Some(&bind_group_layout)],\n            immediate_size: 0,\n        });\n",
    );
    source.push_str(
        "        let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {\n            label: Some(label),\n            layout: Some(&pipeline_layout),\n            module: &shader,\n            entry_point: Some(descriptor.entry_point),\n            compilation_options: Default::default(),\n            cache: None,\n        });\n        Self {\n            _shader: shader,\n            bind_group_layout,\n            _pipeline_layout: pipeline_layout,\n            pipeline,\n        }\n    }\n\n",
    );
    source.push_str("    pub fn encode(\n");
    source.push_str("        &self,\n");
    source.push_str("        device: &wgpu::Device,\n");
    source.push_str("        encoder: &mut wgpu::CommandEncoder,\n");
    // A kernel whose workgroup is two- or three-dimensional takes its extent as `[x, y, z]` (slice m7.d); every other
    // kernel keeps the element count of the one-dimensional host.
    let multi_dimensional = kernel.workgroup_size[1] != 1 || kernel.workgroup_size[2] != 1;
    if multi_dimensional {
        source.push_str("        extent: [u32; 3],\n");
    } else {
        source.push_str("        element_count: u32,\n");
    }
    for parameter in &resources {
        let argument = match parameter.kind {
            ParameterKind::Texture => "&wgpu::TextureView",
            ParameterKind::Sampler => "&wgpu::Sampler",
            _ => "&wgpu::Buffer",
        };
        write_line(
            &mut source,
            format_args!("        {}: {argument},", parameter.name),
        );
    }
    source.push_str("    ) {\n");
    write_line(
        &mut source,
        format_args!(
            "        let label = \"{}::{}\";",
            kernel.module, kernel.name
        ),
    );
    source.push_str("        let bind_group_entries = [\n");
    for parameter in &resources {
        let binding = parameter.binding.expect("validated resource binding");
        source.push_str("            wgpu::BindGroupEntry {\n");
        write_line(
            &mut source,
            format_args!("                binding: {},", binding.binding),
        );
        match parameter.kind {
            ParameterKind::Texture => write_line(
                &mut source,
                format_args!(
                    "                resource: wgpu::BindingResource::TextureView({}),",
                    parameter.name
                ),
            ),
            ParameterKind::Sampler => write_line(
                &mut source,
                format_args!(
                    "                resource: wgpu::BindingResource::Sampler({}),",
                    parameter.name
                ),
            ),
            _ => write_line(
                &mut source,
                format_args!(
                    "                resource: {}.as_entire_binding(),",
                    parameter.name
                ),
            ),
        }
        source.push_str("            },\n");
    }
    source.push_str("        ];\n");
    source.push_str(
        "        let bind_group = device.create_bind_group(&wgpu::BindGroupDescriptor {\n            label: Some(label),\n            layout: &self.bind_group_layout,\n            entries: &bind_group_entries,\n        });\n\n",
    );
    source.push_str(
        "        let mut pass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {\n            label: Some(label),\n            timestamp_writes: None,\n        });\n        pass.set_pipeline(&self.pipeline);\n        pass.set_bind_group(0, &bind_group, &[]);\n",
    );
    if multi_dimensional {
        let [x, y, z] = kernel.workgroup_size;
        write_line(
            &mut source,
            format_args!(
                "        pass.dispatch_workgroups(extent[0].div_ceil({x}), extent[1].div_ceil({y}), \
                 extent[2].div_ceil({z}));"
            ),
        );
    } else {
        write_line(
            &mut source,
            format_args!(
                "        pass.dispatch_workgroups(element_count.div_ceil({}), 1, 1);",
                kernel.workgroup_size[0]
            ),
        );
    }
    source.push_str("    }\n}\n");
    Ok(source)
}

/// Whether the layout entry of `parameter` depends on `float32-filterable`: a sampler, or a sampled float texture (the
/// two layout variants of `texture.rs`).
fn follows_filtering(parameter: &gust::ParameterDescriptor) -> bool {
    parameter.kind == ParameterKind::Sampler
        || parameter
            .resource_layout
            .is_some_and(|layout| match layout.rules {
                gust::ShaderLayoutRules::TextureV1(texture) => {
                    texture.access == gust::TextureAccess::Sampled
                        && texture.class == gust::texture::SampleClass::Float
                }
                _ => false,
            })
}

/// The `ty:` line of a texture or sampler layout entry. The generated `new` takes `float32_filterable` when a kernel
/// has a sampler or a sampled float texture ([`follows_filtering`]) and spells both variants from it: a float texture
/// is `filterable: float32_filterable` and a sampler `Filtering` or `NonFiltering`, as `HeadlessDevice` picks per
/// device. A write-only storage texture stays `WriteOnly`: wgpu refuses `ReadWrite` outside the `r32` formats (D120).
fn render_texture_type(
    target: &mut String,
    parameter: &gust::ParameterDescriptor,
) -> Result<(), Error> {
    if parameter.kind == ParameterKind::Sampler {
        target.push_str(
            "                ty: wgpu::BindingType::Sampler(if float32_filterable {\n                    wgpu::SamplerBindingType::Filtering\n                } else {\n                    wgpu::SamplerBindingType::NonFiltering\n                }),\n",
        );
        return Ok(());
    }
    let texture = parameter
        .resource_layout
        .and_then(|layout| match layout.rules {
            gust::ShaderLayoutRules::TextureV1(texture) => Some(texture),
            _ => None,
        })
        .expect("validated texture layout");
    match (texture.access, texture.format) {
        (gust::TextureAccess::Sampled, _) => {
            let sample_type = match texture.class {
                gust::texture::SampleClass::Uint => "Uint",
                gust::texture::SampleClass::Sint => "Sint",
                _ => "Float { filterable: float32_filterable }",
            };
            write_line(
                target,
                format_args!(
                    "                ty: wgpu::BindingType::Texture {{ sample_type: \
                     wgpu::TextureSampleType::{sample_type}, view_dimension: \
                     wgpu::TextureViewDimension::D2, multisampled: false }},"
                ),
            );
        }
        (access, Some(format)) => {
            let access = if access == gust::TextureAccess::ReadWrite {
                "ReadWrite"
            } else {
                "WriteOnly"
            };
            // The wgpu name comes from the backend's one mapping (`texture::wgpu_format`), not a second table.
            let format = crate::texture::mapped_format(parameter.name, format)?;
            write_line(
                target,
                format_args!(
                    "                ty: wgpu::BindingType::StorageTexture {{ access: \
                     wgpu::StorageTextureAccess::{access}, format: wgpu::TextureFormat::{format:?}, \
                     view_dimension: wgpu::TextureViewDimension::D2 }},"
                ),
            );
        }
        (_, None) => unreachable!("a validated storage texture has a format"),
    }
    Ok(())
}

fn render_struct_fields(
    target: &mut String,
    path: &str,
    layout: gust::TypeLayout,
    base_offset: u32,
) {
    if let gust::TypeLayoutKind::Struct(fields) = layout.kind {
        for field in fields {
            let path = format!("{path}.{}", field.name);
            let offset = base_offset + field.offset;
            write_line(
                target,
                format_args!(
                    "//   {path}: {} @ byte {offset} (size={})",
                    field.ty.name, field.ty.size
                ),
            );
            render_struct_fields(target, &path, field.ty, offset);
        }
    }
}

fn rust_type_identifier(value: &str) -> String {
    let mut result = String::new();
    let mut uppercase_next = true;
    for character in value.chars() {
        if !character.is_ascii_alphanumeric() {
            uppercase_next = true;
        } else if uppercase_next {
            result.push(character.to_ascii_uppercase());
            uppercase_next = false;
        } else {
            result.push(character);
        }
    }
    result
}

fn write_line(target: &mut String, arguments: fmt::Arguments<'_>) {
    target
        .write_fmt(arguments)
        .expect("writing into a String cannot fail");
    target.push('\n');
}
