        assert_eq!(offset_of!(IVec4, w), 12);
        assert_eq!(offset_of!(Vec3, z), 8);
        assert_eq!(offset_of!(UVec3, z), 8);
        assert_eq!(offset_of!(Mat2, cols), 0);
